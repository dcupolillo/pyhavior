class SerialMessages:
    """
    Class to define serial messages as attributes
    for easy readability and maintenance.
    These messages correspond to commands defined
    in an Arduino sketch for controlling various functions
    such as tone, white noise, pump, and shock. The "off" command for
    each function is generated by adding 10 to the "on" command number.

    Attributes are generated dynamically for on/off commands.
    """

    CMD_SUFFIX: str = '\r'

    def __init__(
            self
    ) -> None:

        # Tone message
        (
            self.tone_on,
            self.tone_off
        ) = self._build_commands(1)

        # White noise message
        (
            self.white_noise_on,
            self.white_noise_off
        ) = self._build_commands(2)

        # Pump message
        (
            self.pump_on,
            self.pump_off
        ) = self._build_commands(3)

        # Buzzer message
        (
            self.buzzer_on,
            self.buzzer_off
        ) = self._build_commands(4)

        # Shocker message
        (
            self.shock_on,
            self.shock_off
        ) = self._build_commands(5)

        # Green LED
        (
            self.greenLED_on,
            self.greenLED_off
        ) = self._build_commands(8)

        # Reed LED
        (
            self.redLED_on,
            self.redLED_off
        ) = self._build_commands(9)

    def _build_commands(
            self,
            base_command: int
    ) -> (bytes, bytes):
        """
        Builds the "on" and "off" command strings for a given function.

        Parameters
        ----------
        base_command : int
            The base command number for the "on" command.
            The "off" command is assumed to be this number + 10.

        Returns
        -------
        tuple
            A tuple containing the "on" and "off" commands as bytes objects,
            suitable for serial transmission.
        """
        on_command = bytes(f'{base_command}{self.CMD_SUFFIX}', 'utf-8')
        off_command = bytes(f'{base_command + 10}{self.CMD_SUFFIX}', 'utf-8')

        return on_command, off_command

    def __repr__(
            self
    ) -> str:

        attrs = [
            f"{attr} = {value}"
            for attr, value in self.__dict__.items()]

        return f"{self.__class__.__name__}({', '.join(attrs)})"


class SensorStateDecoder:
    """
    A class to interpret incoming serial bytes from an Arduino, representing
    various sensor states or responses. This class uses explicit attributes
    to maintain a clear and manageable structure for different sensor states.
    """

    def __init__(
            self
    ) -> None:

        (
            self.back_sensor_active,
            self.back_sensor_inactive
        ) = self._build_decoder(5)

        (
            self.side_sensor_active,
            self.side_sensor_inactive
        ) = self._build_decoder(6)

        (
            self.nose_sensor_active,
            self.nose_sensor_inactive
        ) = self._build_decoder(7)

        self.sensors = [
            'Back Sensor',
            'Side Sensor',
            'Nose Sensor']

        self.states = ['Inactive', 'Active']

    def _build_decoder(
            self,
            base_decoder: int
    ) -> (str, str):
        """
        Builds the "on" and "off" state decoder strings.

        Parameters
        ----------
        base_decoder : int
            The base decoder number for the "active" state.
            The "off" state is assumed to be this number + 10.

        Returns
        -------
        tuple
            A tuple containing the "on" and "off" commands as string objects
        """
        on_command = str(base_decoder)
        off_command = str(base_decoder + 10)

        return on_command, off_command

    def interpret(
            self,
            data_str: str
    ) -> str:
        """
        Interprets a single byte of data received from the Arduino.

        Parameters:
        -----------
        data_str : int
            A single byte received from the Arduino's serial output.

        Returns:
        --------
        str
            The human-readable state or command associated with the byte.
        """

        if data_str == self.back_sensor_active:
            return {self.sensors[0]: self.states[1]}
        elif data_str == self.back_sensor_inactive:
            return {self.sensors[0]: self.states[0]}
        elif data_str == self.side_sensor_active:
            return {self.sensors[1]: self.states[1]}
        elif data_str == self.side_sensor_inactive:
            return {self.sensors[1]: self.states[0]}
        elif data_str == self.nose_sensor_active:
            return {self.sensors[2]: self.states[1]}
        elif data_str == self.nose_sensor_inactive:
            return {self.sensors[2]: self.states[0]}

    def __repr__(
            self
    ) -> str:

        attrs = [
            f"{attr} = {value}"
            for attr, value in self.__dict__.items()]

        return f"{self.__class__.__name__}({', '.join(attrs)})"


